import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,writeFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {pathToFileURL} from 'node:url';
import {launchBrowser,createPage} from './helpers/cdp.mjs';

test('缺项提示五秒消失、可关闭、拖动缩放不重弹；方法确认时补全并保存重开',{
  skip:process.env.EASYCODE_BROWSER_TEST !== '1',timeout:60000
},async t => {
  const {assemble,loadBundle} = await import('../scripts/build.mjs');
  const {Model:M,Serialization:S} = globalThis.EasyCode;
  const project = M.createProject('提示测试'), module = M.createModule({name:'看板界面'});
  module.interfaces.push({...M.createInterface(),name:'',englishName:'',purpose:''}); project.modules.push(module);
  const output = await mkdtemp(join(tmpdir(),'easycode-feedback-')), file = join(output,'canvas.html');
  t.diagnostic(`Warning UI artifacts: ${output}`); await writeFile(file,assemble(project,await loadBundle()));
  const browser = await launchBrowser(); t.after(() => browser.close()); const page = await createPage(browser);
  await page.navigate(pathToFileURL(file).href);
  assert.equal(await page.evaluate('document.querySelector("#ec-warnings").hidden'),false);
  assert.match(await page.evaluate('document.querySelector("#ec-warning-text").textContent'),/2 处待补充/);
  const shot = await page.send('Page.captureScreenshot',{format:'png',captureBeyondViewport:false});
  await writeFile(join(output,'warning-with-close.png'),Buffer.from(shot.data,'base64'));
  const started = Date.now();
  await page.click('[data-action="zoom-in"]');
  await page.drag('.node-grip',20,10);
  await page.waitFor('document.querySelector("#ec-warnings").hidden');
  assert.ok(Date.now() - started >= 4400,'the real five-second timer is used');
  assert.ok(Date.now() - started < 7000,'layout changes do not restart the timer');
  await page.click('[data-action="zoom-out"]');
  assert.equal(await page.evaluate('document.querySelector("#ec-warnings").hidden'),true);
  const afterTimer = await page.send('Page.captureScreenshot',{format:'png',captureBeyondViewport:false});
  await writeFile(join(output,'warning-hidden.png'),Buffer.from(afterTimer.data,'base64'));
  await page.navigate(pathToFileURL(file).href);
  await page.click('#ec-warning-close'); await page.click('[data-action="zoom-in"]');
  assert.equal(await page.evaluate('document.querySelector("#ec-warnings").hidden'),true,'manual close survives layout updates');
  const before = await page.evaluate('EasyCode.app.project');
  await page.click('.module-node [data-node-action="edit"]');
  await page.click('#ec-dialog [data-editor-group="methods"] > .fold-heading .fold-toggle');
  await page.click('#ec-dialog .interface-editor > .fold-heading .fold-toggle');
  await page.click('#ec-dialog [aria-label="取消"]'); assert.deepEqual(await page.evaluate('EasyCode.app.project'),before);
  await page.click('.module-node [data-node-action="edit"]');
  await page.click('#ec-dialog [aria-label="确定"]');
  const saved = await page.evaluate('EasyCode.app.project');
  assert.deepEqual(M.validate(saved),{errors:[],warnings:[]});
  const method = saved.modules[0].interfaces[0];
  assert.equal(method.name,'方法1'); assert.equal(method.englishName,'method1'); assert.equal(method.purpose,'方法用途说明');
  assert.equal(method.id,module.interfaces[0].id); assert.equal(saved.modules[0].name,'看板界面');
  assert.equal(await page.evaluate('document.querySelector("#ec-warnings").hidden'),true);
  const html = await page.evaluate('EasyCode.Serialization.buildDocument(JSON.parse(document.getElementById("ec-bundle").textContent),EasyCode.app.project)');
  assert.deepEqual(S.readProject(html),saved);
  const reopened = join(output,'reopened.html'); await writeFile(reopened,html); await page.navigate(pathToFileURL(reopened).href);
  assert.equal(await page.evaluate('document.querySelector("#ec-warnings").hidden'),true);
  await page.click('.module-node [data-node-action="edit"]'); await page.click('#ec-dialog [aria-label="添加方法"]');
  await page.click('#ec-dialog [aria-label="确定"]');
  const methods = await page.evaluate('EasyCode.app.project.modules[0].interfaces');
  assert.deepEqual(methods.map(item => item.englishName),['method1','method2']);
  assert.equal(await page.evaluate('document.querySelector("#ec-warnings").hidden'),true);
  assert.deepEqual(page.pageErrors,[]); assert.deepEqual(page.consoleErrors,[]); assert.deepEqual(page.protocolErrors,[]);
  assert.equal(page.networkRequests.length,0);
});
